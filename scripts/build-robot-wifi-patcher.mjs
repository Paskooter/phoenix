#!/usr/bin/env node
// Bundle only the syntax parser, retaining readable patch logic and Node 4 APIs.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { minify } from 'terser';
const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const parser = readFileSync(require.resolve('acorn'), 'utf8');
const license = readFileSync(new URL('../LICENSE', new URL(require.resolve('acorn'), 'file:')), 'utf8');
const { code } = await minify(parser, { ecma: 5, compress: false, mangle: true, format: { comments: false, max_line_len: 200 } });
const source = readFileSync(new URL('scripts/robot-client-src/patch-ssm-wifi-check.cjs', root), 'utf8')
  .replace(/^#![^\n]+\n/, '')
  .replace("var acorn = require('acorn'); // replaced with the bundled parser by the builder", 'var acorn = phoenixAcorn;');
const output = '#!/usr/bin/env node\n\'use strict\';\n// GENERATED by scripts/build-robot-wifi-patcher.mjs. Edit robot-client-src instead.\n' +
  '/* Bundled Acorn 8.15.0 (MIT), license:\n' + license + '*/\n' +
  'var phoenixAcorn = (function() { var exports = {}; var module = { exports: exports };\n' + code + '\nreturn module.exports; })();\n' + source;
const target = new URL('scripts/robot-client/patch-ssm-wifi-check.cjs', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Wi-Fi patcher bundle is stale; rebuild it and update the public SHA-256 pin');
} else writeFileSync(target, output);
