#!/usr/bin/env node

// Stage a captured local household into a new Phoenix Account store file.
// This command never writes the configured live store and accepts no
// credentials on its command line; the adopted robot key pair is read from the
// current store and transferred only after all validation has passed.

import {
  HouseholdImportError,
  stageHouseholdImport,
} from '../packages/account/src/householdImport.js';

function usage() {
  return `Usage:
  node scripts/import-household-snapshot.mjs --current FILE --root FILE --users FILE
    --output NEW_FILE [--backup BACKUP_FILE]
  node scripts/import-household-snapshot.mjs --current FILE --root FILE --users FILE --dry-run

The command stages a 0600 output and an exact 0600 backup of FILE. It never
changes FILE, and robot credentials are taken from the existing adopted robot
record rather than supplied or generated by this command.

Options:
  --current FILE   Existing Phoenix account store (read only)
  --root FILE      Captured /jibo/loop root JSON (read only)
  --users FILE     Captured /jibo/loop user-node JSON (read only)
  --output FILE    New staged account store
  --backup FILE    New exact backup (default: <output>.backup)
  --dry-run        Validate and report without creating output files
  --help           Show this help
`;
}

function parseArgs(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--help' || arg === '-h') {
      console.log(usage());
      process.exit(0);
    }
    if (arg === '--dry-run') {
      options.dryRun = true;
      continue;
    }
    const match = /^--(current|root|users|output|backup)(?:=(.*))?$/.exec(arg);
    if (!match) throw new Error(`unknown option ${arg}`);
    const value = match[2] === undefined ? argv[++index] : match[2];
    if (!value || value.startsWith('--')) throw new Error(`${arg} requires a file path`);
    options[match[1] === 'root' ? 'rootPath' : match[1] === 'users' ? 'usersPath' : `${match[1]}Path`] = value;
  }
  for (const key of ['currentPath', 'rootPath', 'usersPath']) {
    if (!options[key]) throw new Error(`--${key.slice(0, -4)} is required`);
  }
  if (!options.dryRun && !options.outputPath) throw new Error('--output is required unless --dry-run is used');
  return options;
}

try {
  const result = stageHouseholdImport(parseArgs(process.argv.slice(2)));
  console.log(JSON.stringify({ ok: true, ...result.summary }, null, 2));
} catch (error) {
  const body = {
    ok: false,
    error: error instanceof HouseholdImportError
      ? { code: error.code, message: error.message, details: error.details }
      : { code: error.code || 'IMPORT_FAILED', message: error.message },
  };
  console.error(JSON.stringify(body, null, 2));
  process.exitCode = 1;
}
