function chunk(type,data) {
  const b=Buffer.alloc(data.length+12); b.writeUInt32BE(data.length); b.write(type,4); data.copy(b,8);
  let crc=0xffffffff;
  for(const v of b.subarray(4,-4)) { crc^=v; for(let i=0;i<8;i++)crc=crc&1?0xedb88320^(crc>>>1):crc>>>1; }
  b.writeUInt32BE((crc^0xffffffff)>>>0,b.length-4); return b;
}
export function png(w,h,pixel) {
  const raw=Buffer.alloc(h*(w*4+1)), header=Buffer.alloc(13);
  header.writeUInt32BE(w); header.writeUInt32BE(h,4); header[8]=8; header[9]=6;
  for(let y=0;y<h;y++)for(let x=0;x<w;x++)for(const [c,v] of pixel(x,y).entries())raw[y*(w*4+1)+1+x*4+c]=v;
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),chunk('IHDR',header),chunk('IDAT',deflateSync(raw,{level:9})),chunk('IEND',Buffer.alloc(0))]);
}
